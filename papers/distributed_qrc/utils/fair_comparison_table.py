"""Markdown comparison table of phase 05, generated from ``results/fair_comparison.json``.

One table per architecture at its declared headline configuration (SRSR 10,
MRSR 3x20, SRMR 10/2, MRMR 2x5). Every system is listed with its role,
provenance, result scope, successful / expected runs, test MAE (normalized;
mean and sample std over seeds 0-2), matching basis, tuned resources, mean
readout-fit seconds per cell, and comparison status. Paper-reported values come
from ``results/paper_tables.json`` and are labelled as such; they are context,
not part of any decision. Writes ``results/fair_comparison_table.md``.

Usage (from the repository root)::

    python papers/distributed_qrc/utils/fair_comparison_table.py
"""

from __future__ import annotations

import json
from pathlib import Path

PAPER_DIR = Path(__file__).resolve().parents[1]
EXP = {"srsr": "E1", "mrsr": "E2", "srmr": "E3", "mrmr": "E4"}
MACHINE = {
    "srsr": "laptop CPU",
    "mrsr": "laptop CPU",
    "srmr": "NVIDIA L4 (gpu-1)",
    "mrmr": "NVIDIA L4 (gpu-2)",
}
MATCH = "same data/split/features (total neurons, sub-reservoirs) / readout instances / λ protocol"
# system label -> (role, sweep family for timing, tuned resources, matching basis)
SYSTEMS = [
    (
        "quantum_ideal|quantum_kernel_ideal",
        "paper method: fully quantum (ideal); kernel evaluated in closed form",
        "R2",
        "λ (10)",
        MATCH,
    ),
    (
        "classical|quantum_kernel_ideal",
        "paper method: hybrid (classical reservoir + quantum kernel)",
        "R2",
        "λ (10)",
        MATCH,
    ),
    (
        "quantum_ideal|linear",
        "paper method: quantum reservoir + linear ridge",
        "R2",
        "λ (10)",
        MATCH,
    ),
    (
        "classical|linear",
        "paper baseline B0 (ReservoirPy defaults + linear ridge)",
        "R2",
        "λ (10)",
        MATCH,
    ),
    (
        "classical|rbf_kernel",
        "fair baseline B2b (RBF kernel on B0 features)",
        "CLASSICAL",
        "γ×λ (50)",
        MATCH,
    ),
    (
        "quantum_ideal|rbf_kernel",
        "C2 control B2b (RBF kernel on quantum features)",
        "CLASSICAL",
        "γ×λ (50)",
        "identical features to the quantum-kernel cell",
    ),
    (
        "esn_tuned|linear",
        "fair baseline B4 (tuned ESN + linear ridge)",
        "CLASSICAL",
        "12 ESN × λ (120)",
        MATCH,
    ),
    (
        "esn_tuned|rbf_kernel",
        "fair baseline B4 (tuned ESN + RBF kernel)",
        "CLASSICAL",
        "12 ESN × λ, then γ×λ (170)",
        MATCH,
    ),
    (
        "raw_lags|persistence",
        "floor B1 (persistence)",
        "RAW",
        "none",
        "same window, split, normalization; no reservoir",
    ),
    (
        "raw_lags|linear",
        "floor B1 (AR(4) linear ridge)",
        "RAW",
        "λ (10)",
        "same window, split, normalization; no reservoir",
    ),
    (
        "raw_lags|quantum_kernel_ideal",
        "floor B3 (paper product kernel on raw lags, classical)",
        "RAW",
        "λ (10)",
        "same window, split, normalization; no reservoir",
    ),
    (
        "raw_lags|rbf_kernel",
        "floor B3 (RBF kernel on raw lags)",
        "RAW",
        "γ×λ (50)",
        "same window, split, normalization; no reservoir",
    ),
    (
        "photonic|photonic_kernel",
        "MerLin adaptation (phase 04): photonic reservoir + photonic kernel",
        "MERLIN",
        "λ (10)",
        MATCH,
    ),
]


def esc(text: str) -> str:
    """Escape the cell separator for Markdown tables."""

    return text.replace("|", "\\|")


def main() -> int:
    data = json.loads((PAPER_DIR / "results" / "fair_comparison.json").read_text())
    paper = {
        (
            c["architecture"],
            c["configuration"],
            c["reservoir_type"],
            c["readout_type"],
        ): c["mae"]
        for c in json.loads((PAPER_DIR / "results" / "paper_tables.json").read_text())[
            "cells"
        ]
    }
    seconds = data["readout_seconds_per_cell"]
    lines = [
        "# Phase 05 comparison table (generated by `utils/fair_comparison_table.py`)",
        "",
        "Test MAE on the normalized scale, mean ± sample std over seeds 0-2. Every row except",
        "'paper-reported' is locally executed (simulation, full data, 3 seeds = `paper-accurate`",
        "scope for the reproduced cells; independent controls for B1-B4; adaptation for MerLin).",
        "Status: COMMENSURABLE = same task, data, split, metric, selection split and seeds,",
        "in-run anchors identical to R2.",
        "",
    ]
    for arch, a in data["architectures"].items():
        config = a["diebold_mariano"]["configuration"]
        pc = a["per_configuration"][config]
        sel = a["eval_selected"][config]
        lines += [
            f"## {arch.upper()} {config} ({EXP[arch]}; reservoir and kernel cells on {MACHINE[arch]}, B1/B3 on laptop CPU)",
            "",
            "| System | Role | Provenance | Scope | Successful / expected runs | Test MAE | Std | Matching basis | Tuned resources | Readout fit s/cell | Status |",
            "|---|---|---|---|---:|---:|---:|---|---|---:|---|",
        ]
        for pool, label in (
            ("quantum", "eval-selected quantum/hybrid cell (8-cell pool)"),
            ("fair_classical", "eval-selected fair classical cell (B0-B4 pool)"),
            ("merlin", "eval-selected MerLin photonic cell"),
        ):
            picks = ", ".join(sorted({p["cell"] for p in sel[pool]["picks"]}))
            prov = (
                "local, R2"
                if pool == "quantum"
                else (
                    "local, phase 05 + R2"
                    if pool == "fair_classical"
                    else "local, phase 04"
                )
            )
            scope = "adaptation" if pool == "merlin" else "paper-accurate protocol"
            lines.append(
                f"| **{label}** ({esc(picks)}) | selection by eval RMSE | {prov} | {scope} | 3 / 3 | {sel[pool]['test_mae']['mean']:.5f} | {sel[pool]['test_mae']['std']:.5f} | {MATCH} | per pool | — | COMMENSURABLE |"
            )
        for system, role, family, tuned, matching in SYSTEMS:
            sweep = {
                "R2": f"{EXP[arch]}-R2",
                "CLASSICAL": f"{EXP[arch]}-CLASSICAL",
                "MERLIN": f"{EXP[arch]}-MERLIN",
                "RAW": None,
            }[family]
            key = f"{sweep}|{system}" if sweep else None
            secs = (
                f"{seconds[key]['mean']:.1f}"
                if key and key in seconds
                else "see B1B3-RAW"
            )
            scope = (
                "adaptation"
                if family == "MERLIN"
                else (
                    "independent control"
                    if family in ("CLASSICAL", "RAW")
                    else "paper-accurate protocol"
                )
            )
            prov = {
                "R2": "local, R2 reproduction",
                "CLASSICAL": "local, phase 05",
                "RAW": "local, phase 05",
                "MERLIN": "local, phase 04",
            }[family]
            lines.append(
                f"| `{esc(system)}` | {role} | {prov} | {scope} | 3 / 3 | {pc[system]['mean']:.5f} | {pc[system]['std']:.5f} | {matching} | {tuned} | {secs} | COMMENSURABLE |"
            )
        for system, role in (
            ("classical|linear", "paper baseline B0"),
            ("classical|quantum_kernel_ideal", "paper hybrid"),
            ("quantum_ideal|quantum_kernel_ideal", "paper fully quantum (ideal)"),
        ):
            value = paper.get((arch, config, *system.split("|")))
            if value is not None:
                lines.append(
                    f"| `{esc(system)}` (paper-reported) | {role} | paper Tables C | single run, test-selected reporting | — | {value:.4f} | — | paper's own | unreported | — | PARTIALLY_COMMENSURABLE (context only: single run, normalization and hyperparameters unreported) |"
                )
        dm = [
            r
            for r in a["diebold_mariano"]["rows"]
            if r["loss"] == "abs" and r["lag"] == 24
        ]
        lines += [
            "",
            "Diebold-Mariano (absolute loss, HLN, Newey-West lag 24), eval-selected quantum vs eval-selected fair classical, per seed: "
            + "; ".join(
                f"seed {r['seed']}: DM {r['dm']:+.2f}, p {r['p_value']:.1e}" for r in dm
            )
            + " (positive = the quantum cell has the larger loss).",
            "",
        ]
    lines += [
        "## Claim outcomes (decision rules of the Phase 5 Comparison Plan)",
        "",
        "| Claim | SRSR | MRSR | SRMR | MRMR |",
        "|---|---|---|---|---|",
    ]
    for claim in data["architectures"]["srsr"]["claims"]:
        cells = [
            f"{data['architectures'][a]['claims'][claim]['outcome']} ({data['architectures'][a]['claims'][claim]['counts']['better']}/8 better)"
            for a in EXP
        ]
        lines.append(f"| {claim} | " + " | ".join(cells) + " |")
    headline = [
        data["architectures"][a]["E7_headline_vs_fair_classical"]["mae"] for a in EXP
    ]
    lines.append(
        "| E7 headline MAE reduction vs fair classical (avg / peak) | "
        + " | ".join(
            f"{h['average']['mean']:+.1%} ± {h['average']['std']:.1%} / {h['peak']['mean']:+.1%}"
            for h in headline
        )
        + " |"
    )
    c7 = data["C7"]
    lines += [
        "",
        f"C7 (MRSR 3x20 hybrid): {c7['hybrid_3x20']['mean']:.5f} ± {c7['hybrid_3x20']['std']:.5f} vs fair classical {c7['fair_classical_3x20']['mean']:.5f} ± {c7['fair_classical_3x20']['std']:.5f} → {c7['verdict']} → {c7['outcome']} (paper-reported 0.0113).",
        "",
        "C6 at noise ×10 (fully quantum noisy cell): "
        + "; ".join(
            f"{label}: MRSR vs SRSR {v['mrsr_vs_srsr']['outcome']} ({v['mrsr_vs_srsr']['better']}/8 better), MRMR vs SRSR from 40 {v['mrmr_vs_srsr_from_40']['outcome']} ({v['mrmr_vs_srsr_from_40']['better']}/3)"
            for label, v in data["C6_x10"].items()
        ),
        "",
    ]
    path = PAPER_DIR / "results" / "fair_comparison_table.md"
    path.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
